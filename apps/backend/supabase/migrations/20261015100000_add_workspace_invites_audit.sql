-- Reliable helper invitations and a transparent history of shared job review.

alter table public.workspace_memberships
  add column if not exists member_email text;

create table if not exists public.workspace_invitations (
  id uuid primary key default gen_random_uuid(),
  workspace_owner_id uuid not null references auth.users (id) on delete cascade,
  email text not null,
  member_user_id uuid references auth.users (id) on delete set null,
  status text not null default 'pending' check (status in ('pending', 'accepted', 'revoked')),
  created_at timestamptz not null default now(),
  accepted_at timestamptz,
  constraint workspace_invitations_email_not_blank check (length(trim(email)) > 3)
);

create unique index if not exists workspace_invitations_owner_email_key
  on public.workspace_invitations (workspace_owner_id, lower(email));

create table if not exists public.workspace_job_events (
  id bigint generated by default as identity primary key,
  workspace_owner_id uuid not null references auth.users (id) on delete cascade,
  job_id bigint not null references public.jobs (id) on delete cascade,
  actor_user_id uuid not null references auth.users (id) on delete cascade,
  actor_email text not null,
  action text not null check (action in ('status_changed', 'labels_changed')),
  from_status public."Job Status",
  to_status public."Job Status",
  from_labels text[],
  to_labels text[],
  created_at timestamptz not null default now()
);

create index if not exists workspace_job_events_job_created_idx
  on public.workspace_job_events (job_id, created_at desc);

alter table public.workspace_invitations enable row level security;
alter table public.workspace_job_events enable row level security;

create or replace function public.is_workspace_owner()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select (select auth.uid()) is not null
    and public.current_workspace_owner_id() = (select auth.uid());
$$;

revoke all on function public.is_workspace_owner() from public, anon, authenticated;
grant execute on function public.is_workspace_owner() to authenticated;

create or replace function public.accept_workspace_invitation()
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.workspace_invitations
  set status = 'accepted', accepted_at = coalesce(accepted_at, now())
  where member_user_id = (select auth.uid())
    and status = 'pending';
end;
$$;

revoke all on function public.accept_workspace_invitation() from public, anon, authenticated;
grant execute on function public.accept_workspace_invitation() to authenticated;

drop policy if exists "workspace members can view invitations" on public.workspace_invitations;
create policy "workspace members can view invitations"
on public.workspace_invitations
for select
to authenticated
using (workspace_owner_id = public.current_workspace_owner_id());

drop policy if exists "workspace members can view job events" on public.workspace_job_events;
create policy "workspace members can view job events"
on public.workspace_job_events
for select
to authenticated
using (workspace_owner_id = public.current_workspace_owner_id());

create or replace function public.workspace_update_job_review(
  job_id bigint,
  new_status public."Job Status" default null,
  new_labels text[] default null
)
returns public.jobs
language plpgsql
security definer
set search_path = ''
as $$
declare
  workspace_job public.jobs;
  owner_id uuid;
  actor_email text;
begin
  if (select auth.uid()) is null then
    raise exception 'Authentication required';
  end if;
  if new_status is null and new_labels is null then
    raise exception 'A status or labels update is required';
  end if;

  select j.* into workspace_job
  from public.jobs j
  where j.id = workspace_update_job_review.job_id
    and public.is_workspace_member(j.user_id);
  if workspace_job.id is null then
    raise exception 'Job not found in the current workspace';
  end if;

  owner_id := workspace_job.user_id;
  select u.email into actor_email from auth.users u where u.id = (select auth.uid());

  update public.jobs j
  set status = coalesce(new_status, j.status),
      labels = coalesce(new_labels, j.labels),
      updated_at = now()
  where j.id = workspace_update_job_review.job_id;

  if new_status is not null and new_status is distinct from workspace_job.status then
    insert into public.workspace_job_events
      (workspace_owner_id, job_id, actor_user_id, actor_email, action, from_status, to_status)
    values
      (owner_id, workspace_job.id, (select auth.uid()), coalesce(actor_email, 'unknown'),
       'status_changed', workspace_job.status, new_status);
  end if;

  if new_labels is not null and new_labels is distinct from workspace_job.labels then
    insert into public.workspace_job_events
      (workspace_owner_id, job_id, actor_user_id, actor_email, action, from_labels, to_labels)
    values
      (owner_id, workspace_job.id, (select auth.uid()), coalesce(actor_email, 'unknown'),
       'labels_changed', workspace_job.labels, new_labels);
  end if;

  select j.* into workspace_job from public.jobs j where j.id = workspace_update_job_review.job_id;
  return workspace_job;
end;
$$;

revoke all on function public.workspace_update_job_review(bigint, public."Job Status", text[]) from public, anon, authenticated;
grant execute on function public.workspace_update_job_review(bigint, public."Job Status", text[]) to authenticated;

comment on table public.workspace_job_events is
  'Immutable activity history for shared workspace job review actions.';
